const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');
const root = path.resolve(__dirname,'..');
(async () => {
  const w=new JSDOM('<!doctype html><html><body></body></html>',{url:'http://localhost/',runScripts:'outside-only'}).window;
  let glass=null,calls=0;
  w.Glass={set(v){glass=v}};
  w.Store={signKey: async()=>{calls++;return 'https://example.test/a.png'}};
  w.NEXCHAT_CONFIG={STORAGE_ENDPOINT:''};
  w.eval(fs.readFileSync(path.join(root,'assets/js/ui.js'),'utf8'));
  await w.UI.applyBackground({ui_style:'glass',dash_wallpaper_key:'nexchat/users/me/wallpaper.png'});
  assert.equal(glass,false);assert.equal(calls,0);assert(!w.document.body.classList.contains('has-bg'));
  w.NEXCHAT_CONFIG.STORAGE_ENDPOINT='https://signer.test';
  await w.UI.applyBackground({dash_wallpaper_key:'nexchat/users/me/wallpaper.png'});
  assert.equal(calls,1);assert(w.document.body.classList.contains('has-bg'));
  const html=fs.readFileSync(path.join(root,'tools/legacy-test-fixtures/profile.html'),'utf8');
  assert(!html.includes('data-style="glass"'));assert(html.includes('<b>Classic</b>'));
  w.close();console.log('Classic UI and signer-disabled fallback tests passed.');
})().catch(e=>{console.error(e);process.exit(1)});
